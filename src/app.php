// 2. Database and response helpers
// Domain errors become a plain-language API message with an HTTP status code.
function fail(string $message, int $status = 422): never
{
    throw new DomainException($message, $status);
}
// Open one connection per request and create the current ffms_ tables if needed.
// SQLite is the local default; DB_DSN can select MySQL on a configured server.
function database(): PDO
{
    static $pdo;
    if ($pdo) {
        return $pdo;
    }
    global $store;
    $dsn = getenv('DB_DSN') ?: 'sqlite:' . $store . '/ffms.sqlite';
    $pdo = new PDO($dsn, getenv('DB_USER') ?: null, getenv('DB_PASSWORD') ?: null, [
        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
        PDO::ATTR_EMULATE_PREPARES => false,
    ]);
    $sqlite = $pdo->getAttribute(PDO::ATTR_DRIVER_NAME) === 'sqlite';
    if ($sqlite) {
        $pdo->exec('PRAGMA foreign_keys=ON');
        $pdo->exec('PRAGMA busy_timeout=5000');
    }
    $id = $sqlite ? 'INTEGER PRIMARY KEY AUTOINCREMENT' : 'BIGINT PRIMARY KEY AUTO_INCREMENT';
    $engine = $sqlite ? '' : ' ENGINE=InnoDB';
    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS ffms_users (id $id, tenant_id BIGINT NULL, name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL, role VARCHAR(30) NOT NULL, active INTEGER NOT NULL DEFAULT 1, must_change INTEGER NOT NULL DEFAULT 0, session_version INTEGER NOT NULL DEFAULT 1, created_at VARCHAR(30) NOT NULL)$engine",
    );
    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS ffms_records (id $id, tenant_id BIGINT NOT NULL, module VARCHAR(60) NOT NULL, data TEXT NOT NULL, version INTEGER NOT NULL DEFAULT 1, archived_at VARCHAR(30) NULL, created_at VARCHAR(30) NOT NULL, updated_at VARCHAR(30) NOT NULL)$engine",
    );
    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS ffms_audit (id $id, tenant_id BIGINT NOT NULL, user_id BIGINT NOT NULL, actor VARCHAR(120) NOT NULL, action VARCHAR(60) NOT NULL, module VARCHAR(60) NOT NULL, record_id BIGINT NULL, before_data TEXT NULL, after_data TEXT NULL, created_at VARCHAR(30) NOT NULL)$engine",
    );
    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS ffms_settings (tenant_id BIGINT PRIMARY KEY, data TEXT NOT NULL)$engine",
    );
    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS ffms_attempts (id $id, identity VARCHAR(64) NOT NULL, attempted_at BIGINT NOT NULL)$engine",
    );
    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS ffms_password_resets (token_hash VARCHAR(64) PRIMARY KEY, user_id BIGINT NOT NULL, password_fingerprint VARCHAR(64) NOT NULL, expires_at BIGINT NOT NULL)$engine",
    );
    return $pdo;
}
// Keep values in prepared-statement parameters instead of concatenating them into SQL.
function sql(string $s, array $args = []): PDOStatement
{
    $q = database()->prepare($s);
    $q->execute($args);
    return $q;
}
function now(): string
{
    return date('c');
}
function jsonValue(mixed $v): string
{
    return json_encode($v, JSON_THROW_ON_ERROR | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
}
